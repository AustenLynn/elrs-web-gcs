const KEY = 'gcs.language';
const valid = value => value === 'es' || value === 'en';
const browserStorage = () => { try { return globalThis.window?.localStorage; } catch { return null; } };
export function resolveLanguage({storage, deviceLanguage} = {}) {
  try { const saved = storage?.getItem(KEY); if (valid(saved)) return saved; } catch { /* blocked site storage */ }
  return /^es(?:-|$)/i.test(deviceLanguage ?? '') ? 'es' : 'en';
}
let language = resolveLanguage({storage: browserStorage(), deviceLanguage: globalThis.navigator?.language});
const listeners = new Set();
export const getLanguage = () => language;
export function setLanguage(next) {
  if (!valid(next)) return;
  try { browserStorage()?.setItem(KEY, next); } catch { /* selection remains usable */ }
  if (next === language) return;
  language = next;
  for (const callback of listeners) callback(language);
}
export function onLanguageChange(callback) {
  listeners.add(callback);
  return () => listeners.delete(callback);
}
export function t(key, vars = {}) {
  const text = CATALOGS[language][key] ?? CATALOGS.en[key] ?? key;
  return text.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name) => Object.hasOwn(vars, name) ? String(vars[name]) : match);
}
const documents = new WeakSet();
/** Translate only explicitly marked application labels; never inspect arbitrary DOM text. */
export function initLanguageUI(doc) {
  if (documents.has(doc)) return;
  documents.add(doc);
  const apply = () => {
    doc.documentElement.lang = language;
    for (const el of doc.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const attr of ['title', 'aria-label', 'placeholder', 'content']) {
      for (const el of doc.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
    }
    for (const select of doc.querySelectorAll('[data-language-select]')) select.value = language;
  };
  for (const select of doc.querySelectorAll('[data-language-select]')) select.addEventListener('change', () => { setLanguage(select.value); select.blur(); });
  onLanguageChange(apply);
  apply();
}
